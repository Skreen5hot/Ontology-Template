"""Generate the Protégé entry point: an edit file and its XML catalog.

    python tools/ontology/protege.py           # write protege/
    python tools/ontology/protege.py --check   # exit 1 if stale

The modules import nothing -- vendoring replaces owl:imports, so that no
check depends on the network -- which means a module opened alone in
Protégé shows no BFO or CCO above its classes. protege/edit.ttl imports
every authored module and every vendored file by its ontology IRI, and
protege/catalog-v001.xml maps each of those IRIs to the local file. Open
protege/edit.ttl: Protégé reads the catalog beside it, loads everything
offline, and saves an edit back into the module it belongs to.

Generated rather than written, because both files list paths and IRIs
the layout contract and the modules already hold. The edit file itself
declares no term, and is not in the ontology's scope.

Protégé rewrites a module in its own Turtle on save, comments dropped.
See tools/ontology/normalize.py for keeping such modules in one form.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from xml.sax.saxutils import quoteattr

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import layout  # noqa: E402
import project  # noqa: E402

GENERATOR = "tools/ontology/protege.py"
DIRECTORY = "protege"
EDIT = "protege/edit.ttl"
CATALOG = "protege/catalog-v001.xml"


class Refused(SystemExit):
    """A file that should be importable has no ontology IRI."""


def ontology_iri(path: Path) -> str:
    import rdflib

    graph = rdflib.Graph()
    graph.parse(path, format="turtle")
    heads = sorted(str(s) for s in graph.subjects(rdflib.RDF.type,
                                                  rdflib.OWL.Ontology))
    if len(heads) != 1:
        raise Refused(
            "%s declares %d owl:Ontology headers; Protégé imports a file by "
            "its one ontology IRI" % (path.name, len(heads)))
    return heads[0]


def entries(root: Path) -> list[tuple[str, Path]]:
    """(ontology IRI, file) for every module and vendored file, sorted."""
    out = []
    for path in layout.ontology_files() + layout.vendored_files():
        out.append((ontology_iri(path), path))
    iris = [iri for iri, _ in out]
    if len(iris) != len(set(iris)):
        raise Refused("two files declare the same ontology IRI: %s"
                      % sorted({i for i in iris if iris.count(i) > 1}))
    return sorted(out)


def edit_text(items: list) -> str:
    lines = [
        "@prefix owl:     <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs:    <http://www.w3.org/2000/01/rdf-schema#> .",
        "",
        "# Generated by %s -- do not edit." % GENERATOR,
        "#",
        "# Open this file in Protégé to edit the ontology with BFO and CCO",
        "# loaded beneath it. catalog-v001.xml, beside this file, maps every",
        "# import to a local file, so nothing is fetched. An edit is saved to",
        "# the module it belongs to; this file declares no term.",
        "",
        "<%s/edit> a owl:Ontology ;" % project.iri_base(),
        "    rdfs:comment \"Protégé entry point for %s: imports every module "
        "and every vendored file. Generated; declares no term.\" ;"
        % project.load()["title"].replace('"', "'"),
    ]
    for number, (iri, _path) in enumerate(items):
        end = " ." if number == len(items) - 1 else " ;"
        lines.append("    owl:imports <%s>%s" % (iri, end))
    return "\n".join(lines) + "\n"


def catalog_text(root: Path, items: list) -> str:
    base = root / DIRECTORY
    lines = ['<?xml version="1.0" encoding="UTF-8" standalone="no"?>',
             # No "--" inside an XML comment: XML forbids it, and the
             # first version, written with one, was refused by ROBOT's
             # catalog parser -- the one Protégé uses too.
             "<!-- Generated by %s; do not edit. -->" % GENERATOR,
             '<catalog prefer="public" '
             'xmlns="urn:oasis:names:tc:entity:xmlns:xml:catalog">']
    for number, (iri, path) in enumerate(items, 1):
        relative = Path(os.path.relpath(path, base)).as_posix()
        lines.append('    <uri id="m%d" name=%s uri=%s/>'
                     % (number, quoteattr(iri), quoteattr(relative)))
    lines.append("</catalog>")
    return "\n".join(lines) + "\n"


def generated(root: Path) -> dict[str, bytes]:
    items = entries(root)
    return {EDIT: edit_text(items).encode("utf-8"),
            CATALOG: catalog_text(root, items).encode("utf-8")}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    root = layout.repository_root()
    files = generated(root)
    if args.check:
        stale = [name for name, data in files.items()
                 if not (root / name).is_file()
                 or (root / name).read_bytes() != data]
        if stale:
            print("  STALE: %s -- run python %s" % (", ".join(stale),
                                                   GENERATOR))
            return 1
        print("  %s is current" % DIRECTORY)
        return 0
    (root / DIRECTORY).mkdir(exist_ok=True)
    for name, data in files.items():
        (root / name).write_bytes(data)
        print("  wrote %s" % name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
